"""Analysis session model.

A session is the complete, self-contained result of one analysis run. Reports
are pure functions of a session, which keeps report generation independent of
how the analysis was performed.

``SESSION_SCHEMA_VERSION`` is recorded in every report so a future format change
can be detected when re-reading an old result.
"""

from __future__ import annotations

import platform
import sys
import uuid
from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from typing import Any, Optional

SESSION_SCHEMA_VERSION = "1.0"

# Every section of a report is labelled with one of these provenance values so a
# reader can always tell measured data from inferred data.
PROVENANCE_OBSERVED = "observed"
PROVENANCE_RULE = "rule_derived"
PROVENANCE_AI = "ai_inferred"
PROVENANCE_METADATA = "metadata"

PROVENANCE_LEGEND = {
    PROVENANCE_OBSERVED: "Measured directly from captured packets.",
    PROVENANCE_RULE: "Produced by a deterministic rule applied to observed data.",
    PROVENANCE_AI: "Interpretation generated by an AI model; requires human verification.",
    PROVENANCE_METADATA: "Run metadata and configuration recorded for reproducibility.",
}


@dataclass
class AnalysisSession:
    """Complete result of one analysis run."""

    session_id: str
    started_at: str
    source: str
    source_type: str
    capture_format: Optional[str] = None
    tool_version: str = "0.1.0"
    schema_version: str = SESSION_SCHEMA_VERSION

    packet_count: int = 0
    packets_failed: int = 0
    statistics: dict[str, Any] = field(default_factory=dict)
    flows: list[dict[str, Any]] = field(default_factory=list)
    alerts: list[dict[str, Any]] = field(default_factory=list)
    packets: list[dict[str, Any]] = field(default_factory=list)
    ai_analysis: Optional[dict[str, Any]] = None

    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    limitations: list[str] = field(default_factory=list)
    configuration: dict[str, Any] = field(default_factory=dict)
    environment: dict[str, Any] = field(default_factory=dict)
    evidence_summary: dict[str, Any] = field(default_factory=dict)
    duration_seconds: float = 0.0
    packets_truncated: bool = False

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["provenance_legend"] = PROVENANCE_LEGEND
        return data

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "AnalysisSession":
        payload = {k: v for k, v in data.items() if k in cls.__dataclass_fields__}
        return cls(**payload)


def new_session_id() -> str:
    """Create a sortable, unique session identifier."""
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    return f"{stamp}-{uuid.uuid4().hex[:8]}"


def utc_now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def environment_info() -> dict[str, Any]:
    """Record the interpreter and platform for reproducibility."""
    info: dict[str, Any] = {
        "python_version": sys.version.split()[0],
        "platform": platform.platform(),
    }
    try:
        import scapy

        info["scapy_version"] = getattr(scapy, "__version__", "unknown")
    except Exception:  # noqa: BLE001
        info["scapy_version"] = "unavailable"
    return info
